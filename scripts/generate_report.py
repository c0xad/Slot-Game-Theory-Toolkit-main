if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate reports from simulation result files.")
    parser.add_argument("result_files", nargs='+', help="Path(s) to simulation result CSV file(s).")
    parser.add_argument("-o", "--output-dir", default="reports", help="Directory to save the report and plots.")
    # Add arguments for report format (e.g., --format markdown/pdf) if needed

    args = parser.parse_args()

    # Create output directory if it doesn't exist
    if not os.path.exists(args.output_dir):
        os.makedirs(args.output_dir)
        print(f"Created output directory: {args.output_dir}")

    # Load data
    combined_data = load_simulation_data(args.result_files)

    # Perform analysis
    summary = generate_summary_statistics(combined_data)

    # Generate plots
    metrics_to_plot = ['rtp', 'variance', 'hit_frequency', 'bonus_frequency']
    for metric in metrics_to_plot:
        plot_metric_distribution(combined_data, metric, args.output_dir)

    # Generate report
    generate_markdown_report(summary, args.output_dir, args.result_files)

    print("\nScript finished.")

